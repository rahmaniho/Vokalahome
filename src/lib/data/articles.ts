/** متن کامل یک مطلب به‌صورت رشته — برای جستجوی سمت کلاینت. */
export function articleFullText(article: Article) {
  const body = article.sections
    .map((section) => {
      const blocks = section.blocks
        .map((block) => {
          if (block.type === 'paragraph') return block.text;
          if (block.type === 'quote') return block.text;
          return block.items.join(' ');
        })
        .join(' ');
      return `${section.heading} ${blocks}`;
    })
    .join(' ');
  return `${article.title} ${article.excerpt} ${article.category} ${article.tags.join(' ')} ${article.author} ${body}`;
}

