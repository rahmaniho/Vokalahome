/** ظرفیت باقی‌مانده و وضعیت ثبت‌نام. */
export function eventCapacity(event: ClubEvent) {
  const remaining = Math.max(event.capacity - event.registered, 0);
  const percent = Math.min(Math.round((event.registered / event.capacity) * 100), 100);
  return {
    remaining,
    percent,
    isFull: remaining === 0,
    isAlmostFull: remaining > 0 && remaining <= Math.ceil(event.capacity * 0.15),
  };
}
